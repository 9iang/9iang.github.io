const { readdirSync, writeFileSync } = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");

function findPdfs(directory) {
  return readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap(entry => {
    if (/^[._#~]/.test(entry.name) || entry.name.endsWith("~")) return [];

    const relativePath = `${directory}/${entry.name}`;
    if (entry.isDirectory()) return findPdfs(relativePath);
    return entry.isFile() && /\.pdf$/i.test(entry.name) ? [relativePath] : [];
  });
}

const files = ["documents/analysis", "documents/portfolio"].flatMap(findPdfs).sort();
const header = "// Generated by scripts/build-pdf-index.cjs for previews opened from disk.";
writeFileSync(path.join(root, "pdf-index.local.js"), `${header}\nwindow.LOCAL_PDF_FILES = ${JSON.stringify(files, null, 2)};\n`);
console.log(`PDF 列表已更新，共 ${files.length} 份。`);
